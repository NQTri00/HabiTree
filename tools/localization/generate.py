"""Generate typed common copy and Android resources from the reviewed catalog."""
from pathlib import Path
import json,re,sys
from xml.sax.saxutils import escape
from catalog import ROOT, load_catalog

NAMED_PLACEHOLDER = re.compile(r'\{([a-z][a-z0-9_]*)\}')
POSITIONAL_PLACEHOLDER = re.compile(r'\{\d+\}')
ANDROID_FORMATS = {'integer': 'd', 'string': 's'}

def kotlin(value):
    return json.dumps(value,ensure_ascii=False).replace('$','\\$')

def enum_name(key):
    return ''.join(part[:1].upper()+part[1:] for part in key.split('_'))


def normalize_placeholders(key, item):
    placeholders = item.get('placeholders')
    if placeholders is None:
        for locale in ("vi", "en", "en_one"):
            label = item.get(locale) or ""
            if POSITIONAL_PLACEHOLDER.search(label) or NAMED_PLACEHOLDER.search(label):
                raise ValueError(f"Declare named placeholders in {key} ({locale})")
        return item, {}
    if not isinstance(placeholders, dict) or not placeholders:
        raise ValueError(f'Expected named placeholders in {key}')
    for name, argument_type in placeholders.items():
        if (not isinstance(name, str) or not re.fullmatch(r'[a-z][a-z0-9_]*', name)
                or not isinstance(argument_type, str) or argument_type not in ANDROID_FORMATS):
            raise ValueError(f'Invalid named placeholder {name!r} in {key}')
    plural_argument = item.get('pluralArgument')
    if plural_argument is not None:
        types = list(placeholders.values())
        if (type(plural_argument) is not int or not 0 <= plural_argument < len(types)
                or types[plural_argument] != 'integer' or not item.get('en_one')):
            raise ValueError(f'Invalid named plural argument in {key}')
    positions = {name: index for index, name in enumerate(placeholders)}
    normalized = dict(item)
    for language in ('vi', 'en', 'en_one'):
        text = item.get(language)
        if not text:
            continue
        if set(NAMED_PLACEHOLDER.findall(text)) != positions.keys() or POSITIONAL_PLACEHOLDER.search(text):
            raise ValueError(f'Named placeholder mismatch: {key} ({language})')
        normalized[language] = NAMED_PLACEHOLDER.sub(lambda match: '{' + str(positions[match[1]]) + '}', text)
    android_formats = {
        f'{{{index}}}': f'%{index + 1}${ANDROID_FORMATS[argument_type]}'
        for index, argument_type in enumerate(placeholders.values())
    }
    return normalized, android_formats


def android_text(text, formats):
    if formats:
        text = POSITIONAL_PLACEHOLDER.sub(lambda match: formats[match[0]], text.replace('%', '%%'))
    text = text.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    text = text.replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')
    if text.startswith(('@', '?')):
        text = '\\' + text
    if formats and text != text.strip():
        # Quoting a formatted resource keeps Android from trimming a separator.
        text = '"' + text + '"'
    return escape(text)

def generate(allow_incomplete=False):
    catalog=load_catalog()
    missing=[key for key,item in catalog.items() if not item.get('en')]
    if missing and not allow_incomplete:raise SystemExit(f'{len(missing)} English translations remain; refusing release generation.')
    android_formats_by_key = {}
    for key, item in catalog.items():
        item, android_formats_by_key[key] = normalize_placeholders(key, item)
        catalog[key] = item
        for variant in ['en','en_one']:
            if item.get(variant) and sorted(re.findall(r'\{\d+\}',item['vi']))!=sorted(re.findall(r'\{\d+\}',item[variant])):
                raise SystemExit(f'Placeholder mismatch: {key} ({variant})')
    out=ROOT/'shared/src/commonMain/kotlin/com/mamxanh/shared/localization';out.mkdir(parents=True,exist_ok=True)
    header='// Generated by tools/localization/generate.py. Edit localization/strings/*.yaml.\npackage com.mamxanh.shared.localization\n\n'
    keys=list(catalog)
    (out/'TextKey.kt').write_text(header+'enum class TextKey {\n'+',\n'.join('    '+enum_name(key) for key in keys)+'\n}\n',encoding='utf-8')
    code=header+'internal object GeneratedCopy {\n'
    for language in ['vi','en','en_one']:
        code+='    val '+language+' = arrayOf(\n'+',\n'.join('        '+kotlin(item.get(language) or ('' if language=='en_one' else item['vi'])) for item in catalog.values())+'\n    )\n'
    code+='    val pluralArguments = intArrayOf('+','.join(str(item.get('pluralArgument',-1)) for item in catalog.values())+')\n'
    code+='    val storageValues = arrayOf('+','.join(kotlin(item.get('storageValue','')) for item in catalog.values())+')\n'
    code+='    val categories = listOf('+','.join('TextKey.'+enum_name(key) for key,item in catalog.items() if item.get('canonical'))+')\n}\n'
    (out/'GeneratedCopy.kt').write_text(code,encoding='utf-8')
    mapping=json.loads((ROOT/'localization/android-outputs.json').read_text(encoding='utf-8'))
    if mapping['alias'] != 'catalog-key':
        raise ValueError('Managed Android aliases must preserve the catalog key')
    for qualifier,language in mapping['locales'].items():
        target=ROOT/mapping['module']/'src/main/res'/qualifier/mapping['file']
        target.parent.mkdir(parents=True,exist_ok=True)
        rows=[]
        for key,item in catalog.items():
            formats = android_formats_by_key[key]
            text = android_text(item.get(language) or item['vi'], formats)
            format_attribute = '' if formats else ' formatted="false"'
            rows.append(f'    <string name="{key}"{format_attribute}>{text}</string>')
            if formats and item.get('pluralArgument') is not None:
                rows.append(f'    <plurals name="{key}">')
                if language == 'en':
                    singular = android_text(item['en_one'], formats)
                    rows.append(f'        <item quantity="one">{singular}</item>')
                rows.append(f'        <item quantity="other">{text}</item>')
                rows.append('    </plurals>')
        target.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from the shared copy catalog. -->\n<resources>\n'+'\n'.join(rows)+'\n</resources>\n',encoding='utf-8')
    print(f'Generated {len(keys)} typed copy keys; {len(missing)} translations pending.')

if __name__=='__main__':generate('--allow-incomplete' in sys.argv)
