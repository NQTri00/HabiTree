"""Generate typed common copy and Android resources from the reviewed catalog."""
from pathlib import Path
import json,re,sys
from xml.sax.saxutils import escape
from catalog import ROOT,CATALOG

def kotlin(value):
    return json.dumps(value,ensure_ascii=False).replace('$','\\$')

def enum_name(key):
    return ''.join(part[:1].upper()+part[1:] for part in key.split('_'))

def generate(allow_incomplete=False):
    catalog=json.loads(CATALOG.read_text(encoding='utf-8'))
    missing=[key for key,item in catalog.items() if not item.get('en')]
    if missing and not allow_incomplete:raise SystemExit(f'{len(missing)} English translations remain; refusing release generation.')
    for key,item in catalog.items():
        for variant in ['en','en_one']:
            if item.get(variant) and sorted(re.findall(r'\{\d+\}',item['vi']))!=sorted(re.findall(r'\{\d+\}',item[variant])):
                raise SystemExit(f'Placeholder mismatch: {key} ({variant})')
    out=ROOT/'shared/src/commonMain/kotlin/com/mamxanh/shared/localization';out.mkdir(parents=True,exist_ok=True)
    header='// Generated by tools/localization/generate.py. Edit resources/i18n/messages.json.\npackage com.mamxanh.shared.localization\n\n'
    keys=list(catalog)
    (out/'TextKey.kt').write_text(header+'enum class TextKey {\n'+',\n'.join('    '+enum_name(key) for key in keys)+'\n}\n',encoding='utf-8')
    code=header+'internal object GeneratedCopy {\n'
    for language in ['vi','en','en_one']:
        code+='    val '+language+' = arrayOf(\n'+',\n'.join('        '+kotlin(item.get(language) or ('' if language=='en_one' else item['vi'])) for item in catalog.values())+'\n    )\n'
    code+='    val pluralArguments = intArrayOf('+','.join(str(item.get('pluralArgument',-1)) for item in catalog.values())+')\n'
    code+='    val storageValues = arrayOf('+','.join(kotlin(item.get('storageValue','')) for item in catalog.values())+')\n'
    code+='    val categories = listOf('+','.join('TextKey.'+enum_name(key) for key,item in catalog.items() if item.get('canonical'))+')\n}\n'
    (out/'GeneratedCopy.kt').write_text(code,encoding='utf-8')
    for qualifier,language in [('values','vi'),('values-en','en'),('values-vi','vi')]:
        target=ROOT/'core-ui/src/main/res'/qualifier/'app_copy.xml';target.parent.mkdir(parents=True,exist_ok=True)
        rows=[]
        for key,item in catalog.items():
            text=(item.get(language) or item['vi']).replace('\\','\\\\').replace("'","\\'").replace('"','\\"').replace('\n','\\n').replace('\r','\\r').replace('\t','\\t')
            if text.startswith(('@','?')):text='\\'+text
            rows.append(f'    <string name="{key}" formatted="false">{escape(text)}</string>')
        target.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from the shared copy catalog. -->\n<resources>\n'+'\n'.join(rows)+'\n</resources>\n',encoding='utf-8')
    print(f'Generated {len(keys)} typed copy keys; {len(missing)} translations pending.')

if __name__=='__main__':generate('--allow-incomplete' in sys.argv)
